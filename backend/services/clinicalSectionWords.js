function countWords(text) {
  return String(text || '')
    .trim()
    .split(/\s+/)
    .filter(Boolean).length;
}

/** Join paragraphs; pad with EH prose until minWords (cap extras). */
function paragraphsToBudget(paragraphs, sectionNum) {
  const [minW] = SECTION_BUDGETS[sectionNum] || [100, 150];
  const fillers = FILLERS[sectionNum] || FILLERS.default;
  const out = [...paragraphs.filter((p) => String(p).trim())];
  let wc = countWords(out.join(' '));
  let i = 0;
  while (wc < minW && i < fillers.length) {
    out.push(fillers[i]);
    wc = countWords(out.join(' '));
    i += 1;
  }
  return out;
}

